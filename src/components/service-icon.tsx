/** Decorative service/category icon. Unknown keys (e.g. after an edit) fall back to sparkles. */
export function ServiceIcon({ name, className }: { name?: string | null; className?: string }) {
  const Icon = (name && ICONS[name as IconKey]) || Sparkles
  return <Icon aria-hidden className={className} />
}
